// Universities with a medical college that have no explicit entry above get
// the default set plus the medical extra faculties.
export const UNIVERSITIES_WITH_MEDICINE: string[] = [
  "MADONNA",
  "PAMS",
  "EKOMED",
  "GOUU",
  "SPIRITAN",
  "CLIFFORD",
  "RHEMA",
];

// Resolve the faculty list for a school. `shortName` and `type` come from the
// schools seed data.
export function getFacultiesForSchool(
  shortName: string | null | undefined,
  type: InstitutionType,
): string[] {
  if (type === "university" && shortName) {
    const explicit = UNIVERSITY_FACULTIES[shortName.toUpperCase()];
    if (explicit) return explicit;
    if (UNIVERSITIES_WITH_MEDICINE.includes(shortName.toUpperCase())) {
      return [...DEFAULT_UNIVERSITY_FACULTIES, ...UNIVERSITY_MEDICAL_EXTRA];
    }
  }
  return DEFAULT_FACULTIES_BY_TYPE[type];
}
